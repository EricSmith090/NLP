"""Write requirements-lock.txt: the installed versions of this project's
dependency closure (core + ocr + dev extras + torch/torchvision), not the whole
environment. Re-run after changing pyproject.toml or upgrading packages.

    python tools/make_lockfile.py
"""

from __future__ import annotations

import importlib.metadata as md
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXTRAS = ("ocr", "dev")


def project_roots() -> list[str]:
    """Direct requirements from pyproject.toml (core + extras) plus torch/torchvision."""
    import tomllib

    proj = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    reqs = list(proj.get("dependencies", []))
    for extra in EXTRAS:
        reqs += proj.get("optional-dependencies", {}).get(extra, [])
    names = [re.split(r"[\s\[<>=!~(;]", r.strip(), maxsplit=1)[0] for r in reqs]
    return [n for n in names if n] + ["torch", "torchvision"]


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def requirements(dist: md.Distribution, extras: set[str]) -> list[str]:
    out = []
    for req in dist.requires or []:
        name_part, _, marker = req.partition(";")
        marker = marker.strip()
        if marker:
            m = re.search(r"extra\s*==\s*['\"]([^'\"]+)['\"]", marker)
            if m and m.group(1) not in extras:
                continue
            if "extra" not in marker and ("sys_platform" in marker or "platform_system" in marker or "python_version" in marker):
                pass  # keep platform-conditional deps that are installed
        name = re.split(r"[\s\[<>=!~(]", name_part.strip(), maxsplit=1)[0]
        if name:
            out.append(name)
    return out


def main() -> int:
    seen: dict[str, str] = {}
    todo = [(r, set()) for r in project_roots()]
    while todo:
        name, extras = todo.pop()
        key = norm(name)
        if key in seen:
            continue
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            continue
        seen[key] = f"{dist.metadata['Name']}=={dist.version}"
        todo += [(r, set()) for r in requirements(dist, extras)]
    seen.pop("hannom-parallel", None)
    lines = [
        "# Generated by tools/make_lockfile.py from the working environment",
        f"# Python {sys.version.split()[0]} on {sys.platform}. torch/torchvision come from the CUDA 12.6 index:",
        "#   pip install -r requirements-lock.txt --extra-index-url https://download.pytorch.org/whl/cu126",
        *sorted(seen.values(), key=str.lower),
    ]
    (ROOT / "requirements-lock.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(seen)} pinned packages -> requirements-lock.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
